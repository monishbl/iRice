#!/usr/bin/env bash
# Regenerates shell/common/phosphor.js (icon name -> glyph) from Phosphor's web CSS.
set -euo pipefail
VER=2.1.1
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
{
    echo "// Generated by tools/gen-phosphor-map.sh from @phosphor-icons/web@$VER. Do not edit."
    echo ".pragma library"
    echo "var glyphs = {"
    curl -sfL "https://cdn.jsdelivr.net/npm/@phosphor-icons/web@$VER/src/regular/style.css" |
        tr -d '\n' | grep -oE '\.ph-[a-z0-9-]+:before \{ *content: "\\[0-9a-f]+"' |
        sed -E 's/\.ph-([a-z0-9-]+):before \{ *content: "\\([0-9a-f]+)"/    "\1": "\\u\2",/'
    echo "};"
} > "$ROOT/shell/common/phosphor.js"
echo "Wrote $(grep -c '\\u' "$ROOT/shell/common/phosphor.js") icons"
