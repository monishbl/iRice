#!/usr/bin/env bash
# The Material look's generated assets:
#  - material/assets/fonts/MaterialSymbolsRounded.ttf: Material Symbols Rounded
#    (variable: FILL, GRAD, opsz, wght), cut down to the icons in
#    tools/material-symbols-map.txt and renamed "iRice Symbols" (NOTICE there)
#  - shell/common/material-symbols.js: Phosphor name -> Material Symbols glyph
#  - material/assets/fonts/GoogleSansFlex.ttf (variable), renamed "iRice Sans Flex"
#    (its outlines unchanged)
#  - shell/common/MaterialColor.js (shared: the look previews use it too): Google's material-color-utilities bundled
#    for QML (colour schemes from a seed colour, 2025 spec)
# Needs curl, uv and npx (network).
set -euo pipefail
MCU_VER=0.4.0
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FONTS="$ROOT/material/assets/fonts"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
GH=https://raw.githubusercontent.com

curl -sfL -o "$T/msr.ttf" "$GH/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.ttf"
curl -sfL -o "$T/msr.codepoints" "$GH/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints"
curl -sfL -o "$FONTS/LICENSE-material-symbols" "$GH/google/material-design-icons/master/LICENSE"
curl -sfL -o "$T/gsf.ttf" "$GH/google/fonts/main/ofl/googlesansflex/GoogleSansFlex%5BROND%2Copsz%2Cslnt%2Cwdth%2Cwght%5D.ttf"
{ curl -sfL "$GH/google/fonts/main/ofl/googlesansflex/OFL.txt"; echo; curl -sfL "$GH/google/fonts/main/ofl/googlesansflex/TRADEMARKS.md"; } > "$FONTS/LICENSE-google-sans-flex"

# The map, checked against the font; the glyphs it needs
python3 -I - "$ROOT/tools/material-symbols-map.txt" "$T/msr.codepoints" "$ROOT/shell/common/material-symbols.js" "$T/unicodes" <<'PY'
import sys
pairs = [l.split() for l in open(sys.argv[1]) if l.strip() and not l.startswith("#")]
cps = dict(l.split() for l in open(sys.argv[2]))
missing = [m for _, m in pairs if m not in cps]
if missing:
    sys.exit("not in Material Symbols: " + " ".join(missing))
with open(sys.argv[3], "w") as f:
    f.write("// Generated by tools/gen-material.sh from tools/material-symbols-map.txt. Do not edit.\n")
    f.write(".pragma library\n// Phosphor icon name -> Material Symbols Rounded glyph\nvar glyphs = {\n")
    for p, m in pairs:
        f.write('    "%s": "\\u%s",\n' % (p, cps[m]))
    f.write("};\n")
open(sys.argv[4], "w").write("\n".join("U+" + cps[m] for _, m in pairs))
print(len(pairs), "icons")
PY
uv run -q --with fonttools pyftsubset "$T/msr.ttf" --unicodes-file="$T/unicodes" --layout-features='*' --no-hinting --output-file="$T/subset.ttf"
# Its own family name: a system-wide Material Symbols (the full font, same
# name) would otherwise shape with its glyph numbers and draw with ours
uv run -q --with fonttools python3 -I - "$T/subset.ttf" "$FONTS/MaterialSymbolsRounded.ttf" <<'PY'
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1])
for r in f["name"].names:
    if r.nameID in (1, 3, 4, 6, 16):
        r.string = r.toUnicode().replace("Material Symbols Rounded", "iRice Symbols").replace("MaterialSymbolsRounded", "iRiceSymbols")
f.save(sys.argv[2])
PY

# Google Sans Flex under its own family name too, "iRice Sans Flex": another
# copy installed with the same name (end4's has other axes) shaped text with
# its glyph numbers and drew it with ours, garbling it
uv run -q --with fonttools python3 -I - "$T/gsf.ttf" "$FONTS/GoogleSansFlex.ttf" <<'PY'
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1])
for r in f["name"].names:
    if r.nameID in (1, 3, 4, 6, 16, 21, 25):
        r.string = r.toUnicode().replace("Google Sans Flex", "iRice Sans Flex").replace("GoogleSansFlex", "iRiceSansFlex")
f.save(sys.argv[2])
PY

# Colour: bundled (ES2017: QML's engine has no object spread)
cd "$T"
npm pack -q "@material/material-color-utilities@$MCU_VER" >/dev/null
tar xzf material-material-color-utilities-*.tgz
cat > entry.js <<'JS'
import { Hct, argbFromHex, hexFromArgb, MaterialDynamicColors, SchemeTonalSpot, SchemeExpressive, SchemeVibrant, SchemeContent, SchemeNeutral, SchemeFidelity, SchemeMonochrome } from "./package/index.js";
const SCHEMES = { tonalSpot: SchemeTonalSpot, expressive: SchemeExpressive, vibrant: SchemeVibrant, content: SchemeContent, neutral: SchemeNeutral, fidelity: SchemeFidelity, monochrome: SchemeMonochrome };
// Every colour role of a scheme from a seed colour: { primary: "#rrggbb", … }
export function scheme(seedHex, dark, variant, contrast) {
    const S = SCHEMES[variant] || SchemeTonalSpot;
    const s = new S(Hct.fromInt(argbFromHex(seedHex)), !!dark, contrast || 0, "2025", "phone");
    const out = {};
    for (const c of new MaterialDynamicColors().allColors) {
        if (c)
            out[c.name.replace(/_([a-z])/g, (_, x) => x.toUpperCase())] = hexFromArgb(c.getArgb(s));
    }
    // (the 2025 spec dropped these; Material defines scrim and shadow as
    // black, surface variant as the highest container, the tint as primary)
    out.scrim = out.scrim || "#000000";
    out.shadow = out.shadow || "#000000";
    out.surfaceVariant = out.surfaceVariant || out.surfaceContainerHighest;
    out.surfaceTint = out.surfaceTint || out.primary;
    return out;
}
JS
npx -y esbuild@0.24.0 entry.js --bundle --format=iife --global-name=MCU --target=es2017 --minify --legal-comments=none --log-level=warning --outfile=mcu.js
{
    echo "// Generated by tools/gen-material.sh: @material/material-color-utilities@$MCU_VER"
    echo "// (Copyright Google LLC, Apache License 2.0: LICENSES/Apache-2.0.txt; see"
    echo "// THIRD_PARTY_NOTICES.md) bundled and minified. Do not edit. MCU.scheme(seedHex, dark, variant, contrast) -> roles."
    echo ".pragma library"
    cat mcu.js
} > "$ROOT/shell/common/MaterialColor.js"
echo "Wrote fonts, material-symbols.js and MaterialColor.js"
