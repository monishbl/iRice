#!/usr/bin/env bash
# Regenerates shell/common/emoji.js from Unicode's emoji-test.txt (fully-qualified only).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VER=16.0
{
    echo "// Generated by tools/gen-emoji.sh from Unicode emoji-test.txt $VER. Do not edit."
    echo ".pragma library"
    echo "var list = ["
    curl -sfL "https://unicode.org/Public/emoji/$VER/emoji-test.txt" |
        grep '; fully-qualified' |
        sed -E 's/^.*# (\S+) E[0-9.]+ (.*)$/\1\t\2/' |
        awk -F'\t' '{ gsub(/"/, "\\\"", $2); printf "    [\"%s\", \"%s\"],\n", $1, $2 }'
    echo "];"
} > "$ROOT/shell/common/emoji.js"
echo "Wrote $(grep -c '^    \[' "$ROOT/shell/common/emoji.js") emoji"
